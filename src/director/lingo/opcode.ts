/** Normalize a raw opcode byte to its Opcode value. */
export function opcodeFromRaw(raw: number): Opcode {
  const code = raw >= 0x40 ? 0x40 + (raw % 0x40) : raw;
  return code in MNEMONICS ? (code as Opcode) : Opcode.Invalid;
}

export function opcodeMnemonic(op: Opcode): string {
  return MNEMONICS[op] ?? 'invalid';
}

export function isKnownOpcode(raw: number): boolean {
  const code = raw >= 0x40 ? 0x40 + (raw % 0x40) : raw;
  return code in MNEMONICS;
}
