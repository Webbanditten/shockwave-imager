/**
 * Director palettes: built-in system palettes plus CLUT-chunk palettes.
 *
 * Built-in tables ported from tools/palette-extractor/src/system-palettes.ts
 * (authoritative source: ScummVM engines/director/graphics-data.h).
 *
 * Built-in palette IDs are negative member references:
 *   -1 systemMac, -2 rainbow, -3 grayscale, -4 pastels, -5 vivid, -6 ntsc,
 *   -7 metallic, -8 web216, -101 systemWinDir4, -102 systemWin
 */

export interface Palette {
  name: string;
  /** 256 entries of 0xRRGGBB */
  colors: number[];
  /**
   * Number of AUTHORED entries before padding to 256. A CLUT sized to the
   * bitmap depth (16 for a 4-bit member) reports 16 here; built-in/full
   * palettes leave it undefined (treated as 256). Sub-8-bit decoding uses
   * this to decide whether an index needs spreading across a 256-entry
   * palette (grayscale clouds) or maps directly into its own N-colour CLUT
   * (snow rug and other furni with a depth-sized CLUT). See decodeIndexed.
   */
  sourceCount?: number;
}

