const RAMP_STEPS = [0xee, 0xdd, 0xbb, 0xaa, 0x88, 0x77, 0x55, 0x44, 0x22, 0x11];

function rgb(r: number, g: number, b: number): number {
  return (r << 16) | (g << 8) | b;
}

function buildSystemMac(): number[] {
  const colors: number[] = new Array(256);
  // Indices 0-214: 6x6x6 color cube, descending white -> black
  for (let i = 0; i < 215; i++) {
    const r = (5 - Math.floor(i / 36)) * 51;
    const g = (5 - Math.floor((i % 36) / 6)) * 51;
    const b = (5 - (i % 6)) * 51;
    colors[i] = rgb(r, g, b);
  }
  // Red, green, blue, gray ramps
  for (let j = 0; j < 10; j++) {
    colors[215 + j] = rgb(RAMP_STEPS[j]!, 0, 0);
    colors[225 + j] = rgb(0, RAMP_STEPS[j]!, 0);
    colors[235 + j] = rgb(0, 0, RAMP_STEPS[j]!);
    colors[245 + j] = rgb(RAMP_STEPS[j]!, RAMP_STEPS[j]!, RAMP_STEPS[j]!);
  }
  colors[255] = 0;
  return colors;
}

function buildGrayscale(): number[] {
  const colors: number[] = new Array(256);
  for (let i = 0; i < 256; i++) {
    const gray = 255 - i;
    colors[i] = rgb(gray, gray, gray);
  }
  return colors;
}

