let cachedMac: Palette | null = null;
let cachedWin: Palette | null = null;
let cachedGray: Palette | null = null;

export function systemMacPalette(): Palette {
  if (!cachedMac) cachedMac = { name: 'systemMac', colors: buildSystemMac() };
  return cachedMac;
}

export function systemWinPalette(): Palette {
  if (!cachedWin) {
    cachedWin = { name: 'systemWin', colors: WIN_PALETTE.map(([r, g, b]) => rgb(r, g, b)) };
  }
  return cachedWin;
}

export function grayscalePalette(): Palette {
  if (!cachedGray) cachedGray = { name: 'grayscale', colors: buildGrayscale() };
  return cachedGray;
}

/**
 * Resolve a built-in palette by its negative ID.
 * Unimplemented decorative palettes (rainbow, pastels, ...) fall back to
 * systemMac — none are referenced by the Habbo casts.
 */
export function builtinPalette(id: number): Palette {
  switch (id) {
    case -1:
      return systemMacPalette();
    case -3:
      return grayscalePalette();
    case -101:
    case -102:
      return systemWinPalette();
    default:
      return systemMacPalette();
  }
}

/** Build a Palette from CLUT chunk colors, padded/truncated to 256 entries.
 *  sourceCount preserves the authored entry count so sub-8-bit decoding can
 *  tell a depth-sized CLUT (index maps directly) from a full 256 palette
 *  (index scaled across the range). */
export function paletteFromClut(name: string, clutColors: number[]): Palette {
  const sourceCount = Math.min(clutColors.length, 256);
  const colors = clutColors.slice(0, 256);
  while (colors.length < 256) colors.push(0);
  return { name, colors, sourceCount };
}
